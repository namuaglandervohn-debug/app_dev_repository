import { classes, element, forwardControl } from './style';

function icon(name: string) {
  return forwardControl<HTMLElement>(({ fontSize = 'medium', color, titleAccess, ...props }, ref) =>
    element('i', {
      ...props, ref, className: classes('bi', 'bi-' + name, 'hris-icon MuiSvgIcon-root', props.className),
      role: titleAccess ? 'img' : undefined, 'aria-label': titleAccess, 'aria-hidden': titleAccess ? undefined : true,
    }, { fontSize: ({ small: 20, medium: 24, large: 32, inherit: 'inherit' } as any)[fontSize], color: color && color !== 'inherit' ? color + '.main' : color }));
}

